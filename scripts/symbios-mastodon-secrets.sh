# Generate the persistent secrets of Mastodon instances.
#
# Every instance gets its own directory with database, Redis, Rails and Web
# Push secrets. Existing values are never changed: Mastodon breaks sessions,
# encrypted data and push subscriptions when these values rotate. The script
# also refuses a changed LOCAL_DOMAIN, which is immutable in Mastodon.
#
# The OIDC client secret is generated by gen-oidc-client-secret.sh and must
# already exist when this script runs (the playbook orders it that way).

function f_usage {
  cat << EOF
Usage: $(basename "$0") <instance> [<instance> ...]

Generate missing persistent secrets for the named Mastodon instances. The
instance domains are read from the WebUI-managed instances.yml. Existing
secrets are kept, and an existing LOCAL_DOMAIN is checked for changes.

Arguments:
  instance    instance name(s) from the Mastodon Instances tab

Options:
  -h, --help  Show this help and exit

Examples:
  symbios-mastodon-secrets.sh social
  symbios-mastodon-secrets.sh social photos

Output:
  One status line per instance with the path of its secret directory.

Exit codes:
  0   secrets are complete
  1   technical error (missing domain or secret source)
  2   usage error
EOF
}

if [[ "${1:-}" == "--help" || "${1:-}" == "-h" ]]
then
  f_usage
  exit 0
fi

if [[ $# -eq 0 ]]
then
  f_usage >&2
  exit 2
fi

if [[ -r /etc/bash/gaboshlib.include ]]
then
  source /etc/bash/gaboshlib.include
fi
g_script_dir="$(cd "$(dirname "$(readlink -f "${BASH_SOURCE[0]}")")" && pwd)"
if [[ -r "$g_script_dir/symbios-lib.sh" ]]
then
  source "$g_script_dir/symbios-lib.sh"
fi

g_config_dir="${g_config_dir:-/symbios/base-services/symbios-ui/config}"
g_services_root="${g_services_root:-/symbios/services}"
g_instances_file="${g_config_dir}/services/mastodon/instances.yml"
g_service_dir="${g_services_root}/mastodon"

function f_write_secret_if_missing {
  local f_path="$1"
  local f_value="$2"

  if [[ -s "$f_path" ]]
  then
    return 0
  fi
  umask 077
  printf '%s\n' "$f_value" > "$f_path"
  chmod 0600 "$f_path"
}

function f_generate_vapid_keys {
  local f_key_file f_private f_public

  # Web Push expects base64url-encoded EC P-256 keys: the 32 byte private
  # scalar and the 65 byte uncompressed public point.
  f_key_file=$(mktemp)
  if ! openssl ecparam -name prime256v1 -genkey -noout -out "$f_key_file" 2>/dev/null
  then
    rm -f "$f_key_file"
    return 1
  fi
  f_private=$(openssl ec -in "$f_key_file" -outform DER 2>/dev/null | tail -c 32 | base64 -w0 | tr '+/' '-_' | tr -d '=')
  f_public=$(openssl ec -in "$f_key_file" -pubout -outform DER 2>/dev/null | tail -c 65 | base64 -w0 | tr '+/' '-_' | tr -d '=')
  rm -f "$f_key_file"

  if [[ ${#f_private} -ne 43 || ${#f_public} -ne 87 ]]
  then
    return 1
  fi
  printf '%s\n%s\n' "$f_private" "$f_public"
}

if [[ ! -f "$g_instances_file" ]]
then
  g_echo_error "Mastodon instance config not found: $g_instances_file"
  exit 1
fi

for f_name in "$@"
do
  if ! [[ "$f_name" =~ ^[a-z0-9][a-z0-9-]*$ ]]
  then
    g_echo_error "Invalid Mastodon instance name: $f_name"
    exit 2
  fi

  # mikefarah/yq has no --arg flag; pass the validated instance name as an
  # environment variable and read it with strenv() instead.
  f_domain=$(f_name="$f_name" yq -r '.[] | select(.name == strenv(f_name)) | .domain' "$g_instances_file" 2>/dev/null | head -n1)
  if [[ -z "$f_domain" || "$f_domain" == "null" ]]
  then
    g_echo_error "No domain configured for Mastodon instance $f_name"
    exit 1
  fi

  f_secret_dir="${g_service_dir}/${f_name}-secrets"
  f_env_file="${g_service_dir}/${f_name}.env.production"
  f_oidc_password="${g_service_dir}/${f_name}-oidc/oidc_password"
  mkdir -p "$f_secret_dir"
  chmod 0700 "$f_secret_dir"

  if [[ -f "$f_env_file" ]]
  then
    f_old_domain=$(sed -n 's/^LOCAL_DOMAIN=//p' "$f_env_file" | head -n1)
    if [[ -n "$f_old_domain" && "$f_old_domain" != "$f_domain" ]]
    then
      g_echo_error "LOCAL_DOMAIN of Mastodon instance $f_name cannot be changed ($f_old_domain -> $f_domain); create a new instance instead"
      exit 1
    fi
  fi

  if [[ ! -s "$f_oidc_password" ]]
  then
    g_echo_error "Missing OIDC client secret for Mastodon instance $f_name: $f_oidc_password"
    exit 1
  fi

  f_write_secret_if_missing "$f_secret_dir/db_password" "$(openssl rand -hex 32)"
  f_write_secret_if_missing "$f_secret_dir/redis_password" "$(openssl rand -hex 32)"
  f_write_secret_if_missing "$f_secret_dir/secret_key_base" "$(openssl rand -hex 64)"
  f_write_secret_if_missing "$f_secret_dir/otp_secret" "$(openssl rand -hex 32)"
  f_write_secret_if_missing "$f_secret_dir/encryption_deterministic_key" "$(openssl rand -hex 32)"
  f_write_secret_if_missing "$f_secret_dir/encryption_key_derivation_salt" "$(openssl rand -hex 32)"
  f_write_secret_if_missing "$f_secret_dir/encryption_primary_key" "$(openssl rand -hex 32)"

  if [[ ! -s "$f_secret_dir/vapid_private_key" || ! -s "$f_secret_dir/vapid_public_key" ]]
  then
    f_vapid=$(f_generate_vapid_keys) || {
      g_echo_error "Could not generate VAPID keys for Mastodon instance $f_name"
      exit 1
    }
    f_write_secret_if_missing "$f_secret_dir/vapid_private_key" "${f_vapid%%$'\n'*}"
    f_write_secret_if_missing "$f_secret_dir/vapid_public_key" "${f_vapid#*$'\n'}"
  fi

  g_echo_ok "Mastodon secrets up to date: $f_secret_dir"
done
