# Create a transient file and register it for shredding on exit. Call this
# directly, never inside $(...), so the EXIT trap is changed in this process.
function f_secret_tmp {
  local f_prefix="$1" f_target="$2" f_file
  f_file=$(mktemp "${g_tmp:-/tmp}/jellyfin-${f_prefix}-XXXXXX") || return 1
  chmod 0600 "$f_file"
  printf -v "$f_target" '%s' "$f_file"
  g_secret_files+=("$f_file")
  f_secret_cleanup_register
}

function f_urlencode {
  jq -rn --arg f_value "$1" '$f_value | @uri'
}

# Send one Jellyfin API request. The token is written into a private curl
# config file so it never appears in the process list. The HTTP status is
# returned in g_api_code.
function f_api_request {
  local f_method="$1" f_path="$2" f_body="${3:-}" f_out="$4" f_token="${5:-}"
  local f_config f_error f_auth f_try
  g_api_code=""
  f_secret_tmp curl f_config
  f_secret_tmp curlerr f_error
  {
    printf 'request = "%s"\n' "$f_method"
    printf 'url = "%s%s"\n' "$g_base_url" "$f_path"
    printf 'silent\n'
    printf 'show-error\n'
    printf 'connect-timeout = 5\n'
    printf 'max-time = 60\n'
    printf 'header = "Accept: application/json"\n'
    printf 'header = "Content-Type: application/json"\n'
    # Jellyfin 12 disables the legacy X-Emby-* headers by default, so the
    # client metadata and the API token travel in one Authorization header.
    f_auth='header = "Authorization: MediaBrowser Client=\"SymbiOS\", Device=\"SymbiOS\", DeviceId=\"symbios-jellyfin-provision\", Version=\"1.0\"'
    if [[ -n "$f_token" ]]
    then
      f_auth="${f_auth}, Token=\\\"$(cat "$f_token")\\\""
    fi
    printf '%s"\n' "$f_auth"
    if [[ -n "$f_body" ]]
    then
      printf 'data = "@%s"\n' "$f_body"
    fi
    printf 'output = "%s"\n' "$f_out"
    printf 'write-out = "%%{http_code}"\n'
  } > "$f_config"
  # Only GET is safe to retry: Jellyfin 12 can apply a library change and then
  # leave the HTTP response open, so replaying a POST would duplicate it.
  if [[ "$f_method" == "GET" ]]
  then
    for f_try in 1 2 3
    do
      if g_api_code=$(curl --config "$f_config" 2>"$f_error")
      then
        return 0
      fi
      [[ "$f_try" == "3" ]] && break
      sleep 2
    done
  elif g_api_code=$(curl --config "$f_config" 2>"$f_error")
  then
    return 0
  fi
  g_echo_error "Jellyfin API request failed: $(tr '\n' ' ' < "$f_error")"
  return 1
}

function f_expect_code {
  local f_code="$1" f_expected="$2" f_message="$3"
  if [[ "$f_code" != "$f_expected" ]]
  then
    g_echo_error "$f_message (HTTP $f_code)"
    return 1
  fi
}

# Jellyfin does not attach all local cover files during the first library
# scan. One explicit artwork refresh after the scan finishes picks up the
# images. The marker keeps this a one-time operation on later playbook runs.
function f_refresh_artwork {
  local f_marker="${g_config_dir}/.jellyfin-artwork-refreshed"
  local f_tasks f_folders f_library_id f_try

  [[ -f "$f_marker" ]] && return 0

  f_secret_tmp tasks f_tasks
  for f_try in {1..720}
  do
    f_api_request GET "/ScheduledTasks" "" "$f_tasks" "$g_token_file" || return 1
    f_expect_code "$g_api_code" "200" "Could not read the Jellyfin task list" || return 1
    if jq -e '.[] | select(.Name == "Scan Media Library" and .State == "Idle")' "$f_tasks" >/dev/null
    then
      break
    fi
    if [[ "$f_try" == "720" ]]
    then
      g_echo_error "Jellyfin library scan did not finish within six hours"
      return 1
    fi
    sleep 30
  done

  f_secret_tmp folders f_folders
  f_api_request GET "/Library/VirtualFolders" "" "$f_folders" "$g_token_file" || return 1
  f_expect_code "$g_api_code" "200" "Could not read the Jellyfin library list" || return 1
  f_library_id=$(jq -r '.[] | select(.Name == "Music") | .ItemId' "$f_folders")
  if [[ -z "$f_library_id" ]]
  then
    g_echo_error "Jellyfin Music library not found"
    return 1
  fi

  f_api_request POST "/Items/${f_library_id}/Refresh?Recursive=true&ReplaceAllArtwork=true&ReplaceAllImages=true&ImageRefreshMode=FullRefresh&MetadataRefreshMode=None" "" "$f_tasks" "$g_token_file" || return 1
  f_expect_code "$g_api_code" "204" "Could not refresh the Jellyfin local artwork" || return 1

  date -u +'%Y-%m-%dT%H:%M:%SZ' > "$f_marker"
  chmod 0644 "$f_marker"
  g_changed="true"
  g_echo_note "Jellyfin local artwork refresh started"
}

# Movies and series may use online artwork, but only from TMDb. The provider
# order alone does not disable other fetchers, so list the known alternatives
# explicitly as disabled for those two item types.
function f_ensure_tmdb_only {
  local f_config f_current f_desired

  f_secret_tmp config f_config
  f_secret_tmp configcurrent f_current
  f_secret_tmp configdesired f_desired
  f_api_request GET "/System/Configuration" "" "$f_config" "$g_token_file" || return 1
  f_expect_code "$g_api_code" "200" "Could not read the Jellyfin server configuration" || return 1

  # Compare normalized JSON: Jellyfin's raw response and jq output differ in
  # whitespace, so a byte comparison would report a change on every run.
  jq -S '.' "$f_config" > "$f_current" || return 1
  jq -S '(.MetadataOptions // []) |= map(
    if (.ItemType == "Movie" or .ItemType == "Series")
    then
      .MetadataFetcherOrder = ["TheMovieDb"]
      | .ImageFetcherOrder = ["TheMovieDb"]
      | .DisabledMetadataFetchers = ["IMDb", "The Open Movie Database", "TheTVDB"]
      | .DisabledImageFetchers = ["IMDb", "The Open Movie Database", "TheTVDB"]
    else
      .
    end
  )' "$f_config" > "$f_desired" || return 1

  if cmp -s "$f_current" "$f_desired"
  then
    return 0
  fi

  f_api_request POST "/System/Configuration" "$f_desired" "$g_plugin_file" "$g_token_file" || return 1
  f_expect_code "$g_api_code" "204" "Could not restrict Jellyfin movie and series metadata to TMDb" || return 1
  g_changed="true"
  g_metadata_changed="true"
  g_echo_note "Jellyfin movie and series artwork restricted to TMDb"
}

# The old mixed video library is replaced by separate Movies and TV Shows
# libraries. Remove it once; refreshLibrary=false avoids a needless full scan.
function f_remove_library {
  local f_name="$1"
  local f_id

  f_id=$(jq -r --arg f_name "$f_name" '.[]? | select(.Name == $f_name) | .Name // empty' "$g_folders_file")
  [[ -n "$f_id" ]] || return 0
  f_api_request DELETE "/Library/VirtualFolders?name=$(f_urlencode "$f_name")&refreshLibrary=false" "" "$g_plugin_file" "$g_token_file" || return 1
  f_expect_code "$g_api_code" "204" "Could not remove the obsolete $f_name library" || return 1
  g_changed="true"
  g_libraries_changed="true"
  g_echo_note "Removed obsolete Jellyfin library: $f_name"
}

# The Mediathek Downloader writes into the library directories, so all of its
# destinations point at the Movies/TV Shows mounts and in-flight files use the
# dedicated downloads directory. Compare normalized JSON to stay idempotent.
function f_ensure_mediathek_config {
  local f_plugin_id="a31b415a-5264-419d-b152-8c8192a54994"
  local f_config f_current f_desired

  f_secret_tmp mediathekconfig f_config
  f_secret_tmp mediathekcurrent f_current
  f_secret_tmp mediathekdesired f_desired
  f_api_request GET "/Plugins/${f_plugin_id}/Configuration" "" "$f_config" "$g_token_file" || return 1
  f_expect_code "$g_api_code" "200" "Could not read the Mediathek Downloader configuration" || return 1

  jq -S '.' "$f_config" > "$f_current" || return 1
  jq -S \
    --arg f_movies "$g_media_movies" \
    --arg f_tvshows "$g_media_tvshows" \
    --arg f_downloads "$g_media_downloads" \
    '.Paths = ((.Paths // {}) |
      .DefaultDownloadPath = $f_downloads |
      .DefaultSubscriptionShowPath = $f_tvshows |
      .DefaultSubscriptionMoviePath = $f_movies |
      .DefaultManualShowPath = $f_tvshows |
      .DefaultManualMoviePath = $f_movies |
      .TempDownloadPath = $f_downloads)' \
    "$f_config" > "$f_desired" || return 1

  if cmp -s "$f_current" "$f_desired"
  then
    return 0
  fi

  f_api_request POST "/Plugins/${f_plugin_id}/Configuration" "$f_desired" "$g_plugin_file" "$g_token_file" || return 1
  f_expect_code "$g_api_code" "204" "Could not configure the Mediathek Downloader paths" || return 1
  # The plugin caches its configuration; notify it so no restart is needed.
  f_api_request POST "/MediathekViewDL/Plugin/ConfigurationChanged" "" "$g_plugin_file" "$g_token_file" || return 1
  if [[ "$g_api_code" != "204" ]]
  then
    g_echo_error "Could not reload the Mediathek Downloader configuration (HTTP $g_api_code)"
    return 1
  fi
  g_changed="true"
  g_echo_note "Mediathek Downloader library paths configured"
}

# Wait for the local API before touching any configuration.
f_secret_tmp info g_info_file
g_ready="false"
for f_try in {1..30}
do
  f_api_request GET "/System/Info/Public" "" "$g_info_file"
  if [[ "$g_api_code" == "200" ]]
  then
    g_ready="true"
    break
  fi
  sleep 2
done
if [[ "$g_ready" != "true" ]]
then
  g_echo_error "Jellyfin API did not become ready at $g_base_url"
  exit 1
fi

# After a restart the public info can briefly report an incomplete wizard
# while the user database is still loading. Let it settle before touching the
# bootstrap user; a real first start stays false and is completed below.
for f_try in {1..10}
do
  [[ "$(jq -r '.StartupWizardCompleted // false' "$g_info_file")" == "true" ]] && break
  sleep 2
  f_api_request GET "/System/Info/Public" "" "$g_info_file" || true
done

# The first start creates a password-less bootstrap user. Rename it, set its
# password and close the startup wizard before any other API work.
if [[ "$(jq -r '.StartupWizardCompleted // false' "$g_info_file")" != "true" ]]
then
  f_secret_tmp firstuser g_first_user_file
  f_api_request GET "/Startup/User" "" "$g_first_user_file"
  if [[ "$g_api_code" == "200" ]]
  then
    f_secret_tmp userbody g_user_body
    # Secret files may end with a newline; Jellyfin and Authelia hash the
    # password without it. Trim only line endings, never other whitespace.
    jq -n --arg f_name "$g_admin_user" --rawfile f_password "$g_admin_password_file" \
      '{Name: $f_name, Password: ($f_password | rtrimstr("\n") | rtrimstr("\r"))}' > "$g_user_body"
    f_api_request POST "/Startup/User" "$g_user_body" "$g_first_user_file" || exit 1
    if [[ "$g_api_code" != "204" && "$g_api_code" != "403" ]]
    then
      g_echo_error "Could not set the Jellyfin bootstrap password (HTTP $g_api_code)"
      exit 1
    fi
  fi
  f_api_request POST "/Startup/Complete" "" "$g_first_user_file" || exit 1
  f_expect_code "$g_api_code" "204" "Could not complete the Jellyfin startup wizard" || exit 1
  g_changed="true"
  g_echo_note "Jellyfin startup wizard completed"
fi

# Authenticate as the bootstrap admin and keep the token for the remaining
# configuration calls.
f_secret_tmp authbody g_auth_body
f_secret_tmp authresp g_auth_response
jq -n --arg f_name "$g_admin_user" --rawfile f_password "$g_admin_password_file" \
  '{Username: $f_name, Pw: ($f_password | rtrimstr("\n") | rtrimstr("\r"))}' > "$g_auth_body"
f_api_request POST "/Users/AuthenticateByName" "$g_auth_body" "$g_auth_response" || exit 1
f_expect_code "$g_api_code" "200" "Could not authenticate the Jellyfin bootstrap admin" || exit 1
umask 077
jq -er '.AccessToken' "$g_auth_response" > "$g_token_file" || exit 1
chmod 0600 "$g_token_file"

# Artwork-only mode is launched asynchronously by the playbook so a long first
# scan does not block the playbook run.
if [[ "$g_refresh_artwork" == "true" ]]
then
  f_refresh_artwork || exit 1
  if [[ "$g_changed" == "true" ]]
  then
    g_echo_note "jellyfin-provision-changed"
  else
    g_echo_note "jellyfin-provision-unchanged"
  fi
  exit 0
fi

# The SSO-Auth plugin must be loaded before its API can be configured.
f_secret_tmp plugin g_plugin_file
g_plugin_ready="false"
for f_try in {1..10}
do
  f_api_request GET "/sso/OID/GetNames" "" "$g_plugin_file" "$g_token_file"
  if [[ "$g_api_code" == "200" ]]
  then
    g_plugin_ready="true"
    break
  fi
  sleep 2
done
if [[ "$g_plugin_ready" != "true" ]]
then
  g_echo_error "SSO-Auth plugin API is not available at $g_base_url"
  exit 1
fi

# Point the Mediathek Downloader at the writable library directories. It is
# loaded by the same server restart as SSO-Auth, so its config API is ready.
f_ensure_mediathek_config || exit 1

# Configure Authelia as the OIDC provider. The plugin grants Jellyfin admin
# rights to jellyfin-admins and access to jellyfin-users / jellyfin-admins.
f_secret_tmp pluginbody g_plugin_body
jq -n \
  --arg f_endpoint "$g_oidc_endpoint" \
  --arg f_client "$g_client_id" \
  --rawfile f_secret "$g_oidc_secret_file" \
  '{
    oidEndpoint: $f_endpoint,
    oidClientId: $f_client,
    # gen-oidc-client-secret.sh leaves a trailing newline in the password
    # file, but Authelia hashes the password without it.
    oidSecret: ($f_secret | rtrimstr("\n") | rtrimstr("\r")),
    enabled: true,
    enableAuthorization: true,
    enableAllFolders: true,
    enabledFolders: [],
    adminRoles: ["jellyfin-admins"],
    roles: ["jellyfin-users", "jellyfin-admins"],
    enableFolderRoles: false,
    enableLiveTvRoles: false,
    enableLiveTv: false,
    enableLiveTvManagement: false,
    liveTvRoles: [],
    liveTvManagementRoles: [],
    folderRoleMapping: [],
    roleClaim: "groups",
    oidScopes: ["groups"],
    defaultUsernameClaim: "preferred_username",
    schemeOverride: "https",
    disableHttps: false,
    # Authelia does not expose a PAR endpoint; the plugin must use the normal
    # front-channel authorization endpoint instead.
    disablePushedAuthorization: true,
    doNotValidateEndpoints: false,
    doNotValidateIssuerName: false
  }' > "$g_plugin_body"
f_api_request POST "/sso/OID/Add/$(f_urlencode "$g_provider_name")" "$g_plugin_body" "$g_plugin_file" "$g_token_file" || exit 1
if [[ "$g_api_code" != "200" && "$g_api_code" != "204" ]]
then
  g_echo_error "Could not configure the SSO-Auth plugin (HTTP $g_api_code)"
  exit 1
fi

# Show an SSO button on the login page without hiding the local fallback.
g_css='a.raised.emby-button { padding: 0.9em 1em; color: inherit !important; } .disclaimerContainer { display: block; }'
g_login_form="<form action=\"${g_public_url%/}/sso/OID/start/$(f_urlencode "$g_provider_name")\"><button class=\"raised block emby-button button-submit\">Sign in with SSO</button></form>"
f_secret_tmp brandingbody g_branding_body
f_secret_tmp branding g_current_branding
jq -n --arg f_disclaimer "$g_login_form" --arg f_css "$g_css" \
  '{LoginDisclaimer: $f_disclaimer, CustomCss: $f_css, SplashscreenEnabled: false}' > "$g_branding_body"
f_api_request GET "/Branding/Configuration" "" "$g_current_branding" "$g_token_file" || exit 1
if [[ "$g_api_code" == "200" ]]
then
  g_current_login=$(jq -r '.LoginDisclaimer // ""' "$g_current_branding")
