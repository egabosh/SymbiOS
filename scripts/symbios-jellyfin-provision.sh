function f_usage {
  cat << EOF
Usage: $(basename "$0") [options]

Complete Jellyfin first-run setup, configure the SSO-Auth plugin and create
the standard media libraries. Movies and series use TMDb artwork by default;
music and image libraries stay local-only. Secrets are read from files, never
from argv.

Options:
  --base-url URL        Local Jellyfin API URL (default: http://127.0.0.1:8096)
  --config-dir PATH     Jellyfin service dir containing the secret files
  --public-url URL      Public Jellyfin URL for the SSO login button
  --server-name NAME    Jellyfin server name (e.g. jellyfin.<domain>)
  --oidc-endpoint URL   Authelia OIDC issuer URL (https://auth.<domain>)
  --client-id ID        OIDC client id (default: jellyfin)
  --provider-name NAME  SSO-Auth provider name (default: authelia)
  --admin-user NAME     Local bootstrap admin (default: symbios-admin)
  --media-movies PATH   Container path for the movie library
  --media-tvshows PATH  Container path for the TV series library
  --media-downloads PATH Container path for Mediathek download temp files
  --media-audio PATH    Container path for the audio library
  --media-images PATH   Container path for the image library
  --refresh-artwork     Wait for the first scan, then refresh local artwork once
  -h, --help            Show this help

Required options for normal provisioning: --config-dir, --public-url,
--server-name, --oidc-endpoint, --media-movies, --media-tvshows,
--media-downloads, --media-audio, --media-images.
With --refresh-artwork only --config-dir is required. The refresh runs once and
records a marker in the config dir; delete that marker to repeat it.

Files in --config-dir:
  oidc_password           OIDC client secret (generated by the playbook)
  jellyfin_admin_password Bootstrap admin password (generated by the playbook)
  jellyfin_api_token      API token refreshed on every run (0600)

Output:
  Status lines plus a final jellyfin-provision-changed or
  jellyfin-provision-unchanged token for Ansible changed_when.

Exit codes:
  0 success, 1 technical error, 2 usage error.
EOF
}

