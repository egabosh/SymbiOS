# Create a transient file and register it for shredding on exit. Call this
# directly, never inside $(...), so the EXIT trap is changed in this process.
function f_secret_tmp {
  local f_prefix="$1" f_target="$2" f_file
  f_file=$(mktemp "${g_tmp:-/tmp}/jellyfin-${f_prefix}-XXXXXX") || return 1
  chmod 0600 "$f_file"
  printf -v "$f_target" '%s' "$f_file"
  g_secret_files+=("$f_file")
  f_secret_cleanup_register
}

function f_urlencode {
  jq -rn --arg f_value "$1" '$f_value | @uri'
}

# Send one Jellyfin API request. The token is written into a private curl
# config file so it never appears in the process list. The HTTP status is
# returned in g_api_code.
function f_api_request {
  local f_method="$1" f_path="$2" f_body="${3:-}" f_out="$4" f_token="${5:-}"
  local f_config f_error f_auth f_try
  g_api_code=""
  f_secret_tmp curl f_config
  f_secret_tmp curlerr f_error
  {
    printf 'request = "%s"\n' "$f_method"
    printf 'url = "%s%s"\n' "$g_base_url" "$f_path"
    printf 'silent\n'
    printf 'show-error\n'
    printf 'connect-timeout = 5\n'
    printf 'max-time = 60\n'
    printf 'header = "Accept: application/json"\n'
    printf 'header = "Content-Type: application/json"\n'
    # Jellyfin 12 disables the legacy X-Emby-* headers by default, so the
    # client metadata and the API token travel in one Authorization header.
    f_auth='header = "Authorization: MediaBrowser Client=\"SymbiOS\", Device=\"SymbiOS\", DeviceId=\"symbios-jellyfin-provision\", Version=\"1.0\"'
    if [[ -n "$f_token" ]]
    then
      f_auth="${f_auth}, Token=\\\"$(cat "$f_token")\\\""
    fi
    printf '%s"\n' "$f_auth"
    if [[ -n "$f_body" ]]
    then
      printf 'data = "@%s"\n' "$f_body"
    fi
    printf 'output = "%s"\n' "$f_out"
    printf 'write-out = "%%{http_code}"\n'
  } > "$f_config"
  # Only GET is safe to retry: Jellyfin 12 can apply a library change and then
  # leave the HTTP response open, so replaying a POST would duplicate it.
  if [[ "$f_method" == "GET" ]]
  then
    for f_try in 1 2 3
    do
      if g_api_code=$(curl --config "$f_config" 2>"$f_error")
      then
        return 0
      fi
      [[ "$f_try" == "3" ]] && break
      sleep 2
    done
  elif g_api_code=$(curl --config "$f_config" 2>"$f_error")
  then
    return 0
  fi
  g_echo_error "Jellyfin API request failed: $(tr '\n' ' ' < "$f_error")"
  return 1
}

function f_expect_code {
  local f_code="$1" f_expected="$2" f_message="$3"
  if [[ "$f_code" != "$f_expected" ]]
  then
    g_echo_error "$f_message (HTTP $f_code)"
    return 1
  fi
}

# Resolve the technical user password from the central store, or from the
# transient file handed over by the rotation hook. The lib registers the file
# for shredding, so no plaintext survives the process.
function f_resolve_kodi_password {
  if [[ -n "$g_kodi_password_file" ]]
  then
    [[ -s "$g_kodi_password_file" ]] || return 1
    g_kodi_password_file_path="$g_kodi_password_file"
    return 0
  fi
  f_secret_get_to_file "$g_kodi_password_secret" || return 1
  g_kodi_password_file_path="$g_secret_file_path"
}

# Authenticate as the technical user. A fixed DeviceId keeps the session token
# stable across ordinary runs; Jellyfin revokes it when the password changes.
function f_authenticate_kodi {
  local f_target="$1" f_body f_response
  f_secret_tmp kodibody f_body || return 1
  f_secret_tmp kodiresp f_response || return 1
  jq -n --arg f_name "$g_kodi_user" --rawfile f_password "$g_kodi_password_file_path" \
    '{Username: $f_name, Pw: ($f_password | rtrimstr("\n") | rtrimstr("\r"))}' > "$f_body" || return 1
  f_api_request POST "/Users/AuthenticateByName" "$f_body" "$f_response" || return 1
  [[ "$g_api_code" == "200" ]] || return 1
  jq -er '.AccessToken' "$f_response" > "$f_target" || return 1
  chmod 0600 "$f_target"
}

# A stored device token is only reused when the API still accepts it.
function f_kodi_token_valid {
  local f_token_file="$1" f_out
  [[ -s "$f_token_file" ]] || return 1
  f_secret_tmp kodiverify f_out || return 1
  f_api_request GET "/Users/Me" "" "$f_out" "$f_token_file" || return 1
  [[ "$g_api_code" == "200" ]]
}

# Write the device token into the central store through stdin/file, never argv.
function f_store_kodi_token {
  local f_token_file="$1"
  "${g_script_dir}/symbios-secret.sh" put "$g_kodi_token_secret" --file "$f_token_file" >/dev/null 2>&1
}

# Keep the technical user playback-only. Send the complete policy (Jellyfin
# replaces it as a whole) but compare only the keys we own, so fields added by
# a Jellyfin upgrade do not mark every playbook run as changed.
function f_ensure_kodi_policy {
  local f_id="$1" f_user f_current f_desired f_body f_response f_keys
  f_keys='["IsAdministrator","IsDisabled","EnableMediaPlayback","EnableVideoPlaybackTranscoding","EnableAudioPlaybackTranscoding","EnableLiveTvAccess","EnableLiveTvManagement","EnableRemoteControlOfOtherUsers","EnableSharedDeviceControl","EnableContentDeletion","EnableContentDownloading","EnablePublicSharing","EnableMediaConversion","EnableSyncTranscoding"]'
  f_secret_tmp kodiuser f_user || return 1
  f_secret_tmp kodipolicycurrent f_current || return 1
  f_secret_tmp kodipolicydesired f_desired || return 1
  f_secret_tmp kodipolicybody f_body || return 1
  f_secret_tmp kodipolicyresp f_response || return 1
  f_api_request GET "/Users/$f_id" "" "$f_user" "$g_token_file" || return 1
  f_expect_code "$g_api_code" "200" "Could not read the Jellyfin policy for $g_kodi_user" || return 1
  jq -S '.Policy | .IsAdministrator = false
    | .IsDisabled = false
    | .EnableMediaPlayback = true
    | .EnableVideoPlaybackTranscoding = false
    | .EnableAudioPlaybackTranscoding = false
    | .EnableLiveTvAccess = false
    | .EnableLiveTvManagement = false
    | .EnableRemoteControlOfOtherUsers = false
    | .EnableSharedDeviceControl = false
    | .EnableContentDeletion = false
    | .EnableContentDownloading = false
    | .EnablePublicSharing = false
    | .EnableMediaConversion = false
    | .EnableSyncTranscoding = false' "$f_user" > "$f_body" || return 1
  jq -S --argjson f_keys "$f_keys" '.Policy | with_entries(select(.key as $k | $f_keys | index($k)))' "$f_user" > "$f_current" || return 1
  jq -S --argjson f_keys "$f_keys" '. | with_entries(select(.key as $k | $f_keys | index($k)))' "$f_body" > "$f_desired" || return 1
  if cmp -s "$f_current" "$f_desired"
  then
    return 0
  fi
  f_api_request POST "/Users/$f_id/Policy" "$f_body" "$f_response" "$g_token_file" || return 1
  f_expect_code "$g_api_code" "204" "Could not restrict the Jellyfin policy for $g_kodi_user" || return 1
  g_changed="true"
  g_echo_note "Restricted the Jellyfin policy for $g_kodi_user to playback"
}

# Create the technical user on every run, repair a drifted password and keep a
# valid device token in the central store for the WebUI and clients.
function f_ensure_kodi_user {
  local f_users f_id f_body f_response f_create f_auth f_stored_token f_reset="false"
  f_secret_tmp kodiusers f_users || return 1
  f_api_request GET "/Users" "" "$f_users" "$g_token_file" || return 1
  f_expect_code "$g_api_code" "200" "Could not read the Jellyfin user list" || return 1
  f_id=$(jq -r --arg f_name "$g_kodi_user" '.[] | select(.Name == $f_name) | .Id' "$f_users") || return 1

  if [[ -z "$f_id" ]]
  then
    f_secret_tmp kodinewbody f_body || return 1
    f_secret_tmp kodinewresp f_create || return 1
    jq -n --arg f_name "$g_kodi_user" --rawfile f_password "$g_kodi_password_file_path" \
      '{Name: $f_name, Password: ($f_password | rtrimstr("\n") | rtrimstr("\r"))}' > "$f_body" || return 1
    f_api_request POST "/Users/New" "$f_body" "$f_create" "$g_token_file" || return 1
    if [[ "$g_api_code" != "200" && "$g_api_code" != "204" ]]
    then
      g_echo_error "Could not create the Jellyfin technical user $g_kodi_user (HTTP $g_api_code)"
      return 1
    fi
    f_id=$(jq -er '.Id' "$f_create") || return 1
    g_changed="true"
    g_echo_note "Created Jellyfin technical user: $g_kodi_user"
  fi

  f_secret_tmp kodifresh f_auth || return 1
  if ! f_authenticate_kodi "$f_auth"
  then
    # Rotation or a manual edit made the Jellyfin password drift from the
    # store. An admin can set a new password without knowing the old one.
    f_secret_tmp kodipwresetbody f_body || return 1
    f_secret_tmp kodipwresetresp f_response || return 1
    jq -n --rawfile f_password "$g_kodi_password_file_path" \
      '{NewPw: ($f_password | rtrimstr("\n") | rtrimstr("\r"))}' > "$f_body" || return 1
    f_api_request POST "/Users/Password?userId=$(f_urlencode "$f_id")" "$f_body" "$f_response" "$g_token_file" || return 1
    if [[ "$g_api_code" != "200" && "$g_api_code" != "204" ]]
    then
      g_echo_error "Could not reset the Jellyfin password for $g_kodi_user (HTTP $g_api_code)"
      return 1
    fi
    f_authenticate_kodi "$f_auth" || return 1
    f_reset="true"
    g_changed="true"
    g_echo_note "Reset the Jellyfin password for $g_kodi_user from the secret store"
  fi

  f_ensure_kodi_policy "$f_id" || return 1

  f_stored_token=""
  if f_secret_get_to_file "$g_kodi_token_secret"
  then
    f_stored_token="$g_secret_file_path"
  fi
  if [[ -z "$f_stored_token" || "$f_reset" == "true" ]] || ! f_kodi_token_valid "$f_stored_token"
  then
    f_store_kodi_token "$f_auth" || return 1
    g_changed="true"
    g_echo_note "Stored the Jellyfin device token for $g_kodi_user"
  fi
}

# Jellyfin does not attach all local cover files during the first library
# scan. One explicit artwork refresh after the scan finishes picks up the
# images. The marker keeps this a one-time operation on later playbook runs.
function f_refresh_artwork {
  local f_marker="${g_service_dir}/.jellyfin-artwork-refreshed"
  local f_tasks f_folders f_library_id f_try

  [[ -f "$f_marker" ]] && return 0

  f_secret_tmp tasks f_tasks
  for f_try in {1..720}
  do
    f_api_request GET "/ScheduledTasks" "" "$f_tasks" "$g_token_file" || return 1
    f_expect_code "$g_api_code" "200" "Could not read the Jellyfin task list" || return 1
    if jq -e '.[] | select(.Name == "Scan Media Library" and .State == "Idle")' "$f_tasks" >/dev/null
    then
      break
    fi
    if [[ "$f_try" == "720" ]]
    then
      g_echo_error "Jellyfin library scan did not finish within six hours"
      return 1
    fi
    sleep 30
  done

  f_secret_tmp folders f_folders
  f_api_request GET "/Library/VirtualFolders" "" "$f_folders" "$g_token_file" || return 1
  f_expect_code "$g_api_code" "200" "Could not read the Jellyfin library list" || return 1
  f_library_id=$(jq -r '.[] | select(.Name == "Music") | .ItemId' "$f_folders")
  if [[ -z "$f_library_id" ]]
  then
    g_echo_error "Jellyfin Music library not found"
    return 1
  fi

  f_api_request POST "/Items/${f_library_id}/Refresh?Recursive=true&ReplaceAllArtwork=true&ReplaceAllImages=true&ImageRefreshMode=FullRefresh&MetadataRefreshMode=None" "" "$f_tasks" "$g_token_file" || return 1
  f_expect_code "$g_api_code" "204" "Could not refresh the Jellyfin local artwork" || return 1

  date -u +'%Y-%m-%dT%H:%M:%SZ' > "$f_marker"
  chmod 0644 "$f_marker"
  g_changed="true"
  g_echo_note "Jellyfin local artwork refresh started"
}

# Movies and series may use online artwork, but only from TMDb. The provider
# order alone does not disable other fetchers, so list the known alternatives
# explicitly as disabled for those two item types.
function f_ensure_tmdb_only {
  local f_config f_current f_desired

  f_secret_tmp config f_config
  f_secret_tmp configcurrent f_current
  f_secret_tmp configdesired f_desired
  f_api_request GET "/System/Configuration" "" "$f_config" "$g_token_file" || return 1
  f_expect_code "$g_api_code" "200" "Could not read the Jellyfin server configuration" || return 1

  # Compare normalized JSON: Jellyfin's raw response and jq output differ in
  # whitespace, so a byte comparison would report a change on every run.
  jq -S '.' "$f_config" > "$f_current" || return 1
  jq -S '(.MetadataOptions // []) |= map(
    if (.ItemType == "Movie" or .ItemType == "Series")
    then
      .MetadataFetcherOrder = ["TheMovieDb"]
      | .ImageFetcherOrder = ["TheMovieDb"]
      | .DisabledMetadataFetchers = ["IMDb", "The Open Movie Database", "TheTVDB"]
      | .DisabledImageFetchers = ["IMDb", "The Open Movie Database", "TheTVDB"]
    else
      .
    end
  )' "$f_config" > "$f_desired" || return 1

  if cmp -s "$f_current" "$f_desired"
  then
    return 0
  fi

  f_api_request POST "/System/Configuration" "$f_desired" "$g_plugin_file" "$g_token_file" || return 1
  f_expect_code "$g_api_code" "204" "Could not restrict Jellyfin movie and series metadata to TMDb" || return 1
  g_changed="true"
  g_metadata_changed="true"
  g_echo_note "Jellyfin movie and series artwork restricted to TMDb"
}

# The Pi 5 has no hardware video encoder. Software ffmpeg transcoding saturates
# all cores and can trip the hardware watchdog, so keep it to two threads as a
# safety net while clients are moved to direct play.
function f_limit_encoding_threads {
  local f_config f_current f_desired

  f_secret_tmp encodingconfig f_config
  f_secret_tmp encodingcurrent f_current
  f_secret_tmp encodingdesired f_desired
  f_api_request GET "/System/Configuration/Encoding" "" "$f_config" "$g_token_file" || return 1
