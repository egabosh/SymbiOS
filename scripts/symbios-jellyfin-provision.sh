function f_ensure_library {
  local f_name="$1" f_path="$2" f_type="$3" f_internet="$4"
  local f_existing f_body f_verify
  f_existing=$(jq -r --arg f_name "$f_name" '.[]? | select(.Name == $f_name) | (.Locations[0] // .locations[0] // "")' "$g_folders_file")
  if [[ -z "$f_existing" ]]
  then
    # An empty library has no item id yet, so pass the options at creation;
    # f_ensure_library_options cannot address it by id until it has content.
    f_secret_tmp folderbody f_body
    jq -n --argjson f_internet "$f_internet" \
      '{LibraryOptions: {EnableRealtimeMonitor: true, AutomaticRefreshIntervalDays: 0, EnableInternetProviders: $f_internet}}' > "$f_body"
    if ! f_api_request POST "/Library/VirtualFolders?name=$(f_urlencode "$f_name")&collectionType=$(f_urlencode "$f_type")&paths=$(f_urlencode "$f_path")&refreshLibrary=false" "$f_body" "$g_plugin_file" "$g_token_file"
    then
      # Jellyfin 12 can apply the library change and leave the response open.
      # Verify by reading the list back instead of replaying the POST.
      f_secret_tmp verify f_verify
      f_api_request GET "/Library/VirtualFolders" "" "$f_verify" "$g_token_file" || return 1
      f_expect_code "$g_api_code" "200" "Could not verify the $f_name library" || return 1
      if ! jq -e --arg f_name "$f_name" --arg f_path "$f_path" \
        '.[]? | select(.Name == $f_name and .Locations[0] == $f_path)' "$f_verify" >/dev/null
      then
        g_echo_error "Could not create the $f_name library"
        return 1
      fi
      g_echo_note "Jellyfin $f_name library created (API response timed out)"
    elif [[ "$g_api_code" != "204" ]]
    then
      g_echo_error "Could not create the $f_name library (HTTP $g_api_code)"
      return 1
    fi
    g_changed="true"
    g_libraries_changed="true"
    g_echo_note "Created Jellyfin library: $f_name"
  elif [[ "$f_existing" != "$f_path" ]]
  then
    f_secret_tmp folderbody f_body
    jq -n --arg f_name "$f_name" --arg f_path "$f_path" \
      '{Name: $f_name, PathInfo: {Path: $f_path}}' > "$f_body"
    f_api_request POST "/Library/VirtualFolders/Paths/Update" "$f_body" "$g_plugin_file" "$g_token_file" || return 1
    f_expect_code "$g_api_code" "204" "Could not update the $f_name library path" || return 1
    g_changed="true"
    g_libraries_changed="true"
    g_echo_note "Updated Jellyfin library path: $f_name"
  fi
}

